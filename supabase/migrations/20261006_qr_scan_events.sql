create table if not exists public.qr_scan_events (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  event_date date not null default ((now() at time zone 'Europe/Istanbul')::date),
  event_time timestamptz not null default now(),
  event_type text not null default 'invalid',
  message text not null default 'Geçersiz QR kodu okutuldu',
  constraint qr_scan_events_type_check check (event_type in ('invalid'))
);

create index if not exists qr_scan_events_date_idx on public.qr_scan_events(event_date, event_time desc);

alter table public.qr_scan_events enable row level security;

drop policy if exists "Service role manages qr scan events" on public.qr_scan_events;
create policy "Service role manages qr scan events" on public.qr_scan_events
for all to service_role using (true) with check (true);

do $$
begin
  alter publication supabase_realtime add table public.qr_scan_events;
exception when duplicate_object then null;
end $$;
